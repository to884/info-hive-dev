def is_generated(text: str) -> bool:
    head = "\n".join(text.splitlines()[:20]).lower()
    return any(marker in head for marker in GENERATED_MARKERS)


def matches_any(path: Path, patterns: list[str]) -> bool:
    name = path.name
    posix = path.as_posix()
    return any(fnmatch.fnmatch(name, pat) or fnmatch.fnmatch(posix, pat) for pat in patterns)


def iter_docs(paths: list[Path]) -> Iterable[Path]:
    for path in paths:
        if path.is_file():
            if path.suffix.lower() in DOC_EXTENSIONS:
                yield path
            continue
        if path.is_dir():
            for child in path.rglob("*"):
                if child.is_dir():
                    continue
                if child.suffix.lower() not in DOC_EXTENSIONS:
                    continue
                if any(part in IGNORE_DIRS for part in child.parts):
                    continue
                yield child


def select_files(paths: list[Path], include: list[str], exclude: list[str],
                 ignore_generated: bool, max_files: int) -> list[Path]:
    candidates = sorted(set(iter_docs(paths)))
    selected: list[Path] = []
    for path in candidates:
        if include and not matches_any(path, include):
            continue
        if exclude and matches_any(path, exclude):
            continue
        if ignore_generated:
            try:
                if is_generated(read_text(path)):
                    continue
            except OSError:
                continue
        selected.append(path)
    return selected[:max_files] if max_files and max_files > 0 else selected


def read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        return path.read_text(encoding="utf-8", errors="replace")


