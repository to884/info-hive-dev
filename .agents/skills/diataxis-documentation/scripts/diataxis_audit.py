def audit_file(path: Path, root: Path | None = None, patterns: PatternSet | None = None) -> AuditResult:
    patterns = patterns or PatternSet()
    raw = read_text(path)
    rst = path.suffix.lower() in RST_EXTENSIONS
    frontmatter, content = split_frontmatter(raw)
    if path.suffix.lower() == ".mdx":
        content = strip_mdx(content)
    title = extract_title(path, content, frontmatter)
    headings = extract_headings(content, rst)
    body = strip_code(content, rst=rst)
    signals = collect_structural_signals(content, body, headings, rst)
    declared = frontmatter.get("doc_type") or frontmatter.get("type") or None
    doc = ParsedDoc(path=path, title=title, body=body, headings=headings,
                    signals=signals, declared=declared)
    scores = compute_scores(title, body, headings, signals, patterns)
    status, candidates, hypotheses, separation, missing = assess(scores, signals)
    risks = collect_risks(doc, scores, status, candidates)
    suggestions = make_suggestions(status, candidates, risks)
    display_path = str(path)
    if root is not None:
        try:
            display_path = str(path.relative_to(root))
        except ValueError:
            display_path = str(path)
    return AuditResult(
        schema_version=SCHEMA_VERSION,
        path=display_path,
        title=title,
        declared_doc_type=declared,
        classification_status=status,
        candidate_modes=candidates,
        mode_hypotheses=hypotheses,
        signal_separation=separation,
        scores=scores,
        structural_signals=signals,
        risks=risks,
        missing_context=missing,
        suggestions=suggestions,
    )


def escape_md(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")


def status_label(result: AuditResult) -> str:
    """Describe the outcome without implying a confidence.

    The parenthetical describes the *gap between the top two scores*, which is
    what `signal_separation` measures. It is deliberately not phrased as
    strength or confidence in the classification being correct.
    """
    if result.classification_status == "clear":
        margin = "wide margin" if result.signal_separation >= NARROW_MARGIN_BELOW else "narrow margin"
        return f"{result.candidate_modes[0]} ({margin})"
    if result.classification_status == "ambiguous":
        return "ambiguous: " + " + ".join(result.candidate_modes)
    return "insufficient-context"


def markdown_report(results: list[AuditResult]) -> str:
    lines: list[str] = []
    lines.append("# Diátaxis audit")
    lines.append("")
    lines.append(f"Scanned {len(results)} file{'s' if len(results) != 1 else ''}.")
    lines.append("")
    lines.append("These are structural signals, not verdicts. Decide the mode yourself, using the reader's situation.")
    lines.append("")
    lines.append("| File | Title | Declared | Signals suggest | Separation | Risks |")
    lines.append("|---|---|---|---|---:|---:|")
    for result in results:
        lines.append(
            f"| `{escape_md(result.path)}` | {escape_md(result.title)} | "
            f"{escape_md(result.declared_doc_type or '')} | {escape_md(status_label(result))} | "
            f"{result.signal_separation:.2f} | {len(result.risks)} |"
        )
    lines.append("")

    flagged = [r for r in results if r.risks or r.missing_context]
    if flagged:
        lines.append("## Observations to verify")
        lines.append("")
        for result in flagged:
            lines.append(f"### `{result.path}`")
            lines.append("")
            lines.append(f"Signals suggest: **{status_label(result)}**")
            lines.append("")
            sig = result.structural_signals
            lines.append(
                f"Structure: {sig['ordered_steps']} ordered steps, {sig['code_blocks']} code blocks, "
                f"{sig['table_rows']} table rows, {sig['expected_output_checks']} expected-output checks, "
                f"{sig['conditional_branches']} conditional branches, "
                f"{sig['unresolved_placeholders']} unresolved placeholders."
            )
            lines.append("")
            if result.risks:
                lines.append("Risks:")
                for risk in result.risks:
                    lines.append(f"- `{risk['rule']}` ({risk['category']}) — {risk['evidence']}")
                lines.append("")
            if result.missing_context:
                lines.append("Missing context:")
                for item in result.missing_context:
                    lines.append(f"- {item}")
                lines.append("")
            if result.suggestions:
                lines.append("Suggestions:")
                for suggestion in result.suggestions:
                    lines.append(f"- {suggestion}")
                lines.append("")

    return "\n".join(lines)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Collect Diátaxis structural signals and risks from Markdown-like docs.",
        epilog="Output is evidence, not a verdict. Do not use it as a CI compliance gate for mode purity.",
    )
    parser.add_argument("paths", nargs="+", help="Files or directories to audit")
    parser.add_argument("--format", choices=("markdown", "json"), default="markdown", help="Output format")
    parser.add_argument("--max-files", type=int, default=500,
                        help="Maximum number of files to scan, applied after sorting so results are deterministic")
    parser.add_argument("--include", action="append", default=[],
                        help="Only audit files matching this glob (repeatable)")
    parser.add_argument("--exclude", action="append", default=[],
                        help="Skip files matching this glob (repeatable)")
    parser.add_argument("--ignore-generated", action="store_true",
                        help="Skip files whose first 20 lines mark them as generated")
    parser.add_argument("--patterns", type=Path,
                        help="JSON file overriding the built-in title/body/heading pattern sets")
    parser.add_argument("--fail-on", choices=("never", "risks", "placeholders"), default="never",
                        help="Exit non-zero when the named condition is present (default: never). "
                             "'risks' counts only mode-independent 'defect' risks; mode-purity risks "
                             "never affect the exit code.")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)

    input_paths = [Path(p).resolve() for p in args.paths]
    missing = [str(p) for p in input_paths if not p.exists()]
    if missing:
        print(f"Missing path(s): {', '.join(missing)}", file=sys.stderr)
        return 2
    existing = [p for p in input_paths if p.exists()]
    if not existing:
        print("No input paths found.", file=sys.stderr)
        return 2

    patterns = PatternSet.load(args.patterns) if args.patterns else PatternSet()

    dirs = [p if p.is_dir() else p.parent for p in existing]
    try:
        common_root = Path(os.path.commonpath([str(d) for d in dirs]))
    except ValueError:
        common_root = None

    files = select_files(existing, args.include, args.exclude, args.ignore_generated, args.max_files)
    results = [audit_file(path, common_root, patterns) for path in files]

    if args.format == "json":
        print(json.dumps({"schema_version": SCHEMA_VERSION, "results": [asdict(r) for r in results]},
                         indent=2, ensure_ascii=False))
    else:
        print(markdown_report(results))

    if args.fail_on == "risks" and any(
        risk["category"] == DEFECT for r in results for risk in r.risks
    ):
        return 1
    if args.fail_on == "placeholders" and any(int(r.structural_signals["unresolved_placeholders"]) for r in results):
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
