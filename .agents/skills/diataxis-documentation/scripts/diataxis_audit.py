def compute_scores(title: str, body: str, headings: list[str],
                   signals: dict[str, object], patterns: PatternSet) -> dict[str, int]:
    lower_title = title.lower()
    scores = {mode: 0 for mode in MODES}

    for mode, pats in patterns.title.items():
        for pattern, weight in pats:
            if re.search(pattern, lower_title, flags=re.IGNORECASE):
                scores[mode] = scores.get(mode, 0) + weight

    for mode, pats in patterns.body.items():
        for pattern, weight in pats:
            hits = count_pattern(pattern, body)
            scores[mode] = scores.get(mode, 0) + min(hits, 5) * weight

    for mode, pats in patterns.heading.items():
        for heading in headings:
            for pattern in pats:
                if re.search(pattern, heading, flags=re.IGNORECASE):
                    scores[mode] = scores.get(mode, 0) + 3

    ordered_steps = int(signals["ordered_steps"])
    code_blocks = int(signals["code_blocks"])
    table_rows = int(signals["table_rows"])

    if ordered_steps:
        scores["how-to"] += min(ordered_steps, 8) * 2
        scores["tutorial"] += min(ordered_steps, 8)
    if code_blocks:
        for mode in ("tutorial", "how-to", "reference"):
            scores[mode] += min(code_blocks, 5)
    if table_rows:
        scores["reference"] += min(table_rows, 12)
    if int(signals["long_paragraphs"]):
        scores["explanation"] += min(int(signals["long_paragraphs"]), 5) * 2
    if int(signals["bullet_items"]) > 12 and table_rows == 0:
        scores["reference"] += 2
        scores["explanation"] += 1

    return scores


def assess(scores: dict[str, int], signals: dict[str, object]) -> tuple[str, list[str], list[str], float, list[str]]:
    """Return (status, candidate_modes, mode_hypotheses, signal_separation, missing_context).

    ``signal_separation`` is the normalized gap between the top two hand-weighted
    scores. It is NOT a probability that the classification is correct.
    """
    ordered = sorted(scores.items(), key=lambda item: (-item[1], item[0]))
    hypotheses = [mode for mode, score in ordered if score > 0]
    top_mode, top_score = ordered[0]
    second_mode, second_score = ordered[1]
    separation = round(max(0.0, min(1.0, (top_score - second_score) / max(top_score, 1))), 2)

    if top_score <= 2 or int(signals["word_count"]) < 40:
        return (
            "insufficient-context",
            [],
            hypotheses,
            separation,
            [
                "intended reader situation",
                "whether the page is a container/record rather than a mode page",
                "too little content to produce structural signals",
            ],
        )

    if second_score >= 6 and second_score >= top_score * AMBIGUITY_RATIO:
        return (
            "ambiguous",
            [top_mode, second_mode],
            hypotheses,
            separation,
            [
                "intended reader situation",
                "whether the scenario is a controlled exercise or real work",
                "which need the page's navigation position implies",
            ],
        )

    return "clear", [top_mode], hypotheses, separation, []


