def split_frontmatter(text: str) -> tuple[dict[str, str], str]:
    """Parse a leading YAML frontmatter block only.

    Returns (frontmatter mapping of top-level scalar keys, remaining body).
    A ``key: value`` line elsewhere in the document is body text, not
    frontmatter, and is not treated as one.
    """
    lines = text.splitlines()
    idx = 0
    while idx < len(lines) and lines[idx].strip() == "":
        idx += 1
    if idx >= len(lines) or lines[idx].strip() not in {"---", "+++"}:
        return {}, text
    fence = lines[idx].strip()
    for end in range(idx + 1, len(lines)):
        if lines[end].strip() == fence:
            block = lines[idx + 1:end]
            data: dict[str, str] = {}
            for line in block:
                m = re.match(r"^([A-Za-z0-9_.-]+)\s*:\s*(.*)$", line)
                if m:
                    value = m.group(2).strip().strip('"').strip("'")
                    data[m.group(1)] = value
            return data, "\n".join(lines[end + 1:])
    return {}, text


def strip_code(text: str, rst: bool = False) -> str:
    """Remove fenced, indented, and (for RST) literal code blocks.

    Fences follow the same rule as ``docs_health.code_line_flags``: a closing
    fence uses the same character as the opener and is at least as long, so a
    shorter run inside a block is content rather than a close. The two are
    pinned together by ``tests/test_shared_parsing.py``.

    Code lines are blanked rather than deleted, so paragraph boundaries either
    side of a block survive.
    """
    kept: list[str] = []
    fence: str | None = None
    for line in text.splitlines():
        match = re.match(r"^\s{0,3}(`{3,}|~{3,})", line)
        if match:
            token = match.group(1)
            if fence is None:
                fence = token
                kept.append("")
                continue
            if token[0] == fence[0] and len(token) >= len(fence):
                fence = None
                kept.append("")
                continue
        kept.append("" if fence is not None else line)
    text = "\n".join(kept)
    if rst:
        text = re.sub(r"^\.\.\s+\w[\w-]*::.*?(?=^\S|\Z)", "", text, flags=re.DOTALL | re.MULTILINE)
    out_lines = []
    for line in text.splitlines():
        if re.match(r"^(?: {4}|\t)\S", line):
            continue
        out_lines.append(line)
    return "\n".join(out_lines)


def strip_mdx(text: str) -> str:
    """Drop MDX import/export lines and JSX component tags, keeping their text."""
    text = re.sub(r"^\s*(?:import|export)\s+.*$", "", text, flags=re.MULTILINE)
    text = re.sub(r"</?[A-Z][A-Za-z0-9]*(?:\s[^>]*)?/?>", "", text)
    return text


def extract_title(path: Path, text: str, frontmatter: dict[str, str]) -> str:
    title = frontmatter.get("title", "").strip()
    if title:
        return title
    for line in text.splitlines():
        match = re.match(r"^\s*#\s+(.+?)\s*$", line)
        if match:
            return re.sub(r"[`*_{}\[\]()#]", "", match.group(1)).strip()
    lines = text.splitlines()
    for i in range(len(lines) - 1):
        candidate = lines[i].strip()
        underline = lines[i + 1].strip()
        if not candidate:
            continue
        if re.fullmatch(r"[=\-~^#*+`:'\"_]{3,}", underline) and len(underline) >= len(candidate) - 2:
            return candidate
    return path.stem.replace("-", " ").replace("_", " ").strip().title()


def extract_headings(text: str, rst: bool) -> list[str]:
    headings: list[str] = []
    for line in text.splitlines():
        m = re.match(r"^\s{0,3}#{1,6}\s+(.+?)\s*$", line)
        if m:
            headings.append(m.group(1).strip().lower())
    if rst:
        lines = text.splitlines()
        for i in range(len(lines) - 1):
            candidate = lines[i].strip()
            underline = lines[i + 1].strip()
            if not candidate or candidate.startswith(".."):
                continue
            if re.fullmatch(r"[=\-~^#*+`:'\"_]{3,}", underline) and len(underline) >= len(candidate) - 2:
                headings.append(candidate.lower())
    return headings


def count_pattern(pattern: str, text: str) -> int:
    return len(re.findall(pattern, text, flags=re.IGNORECASE | re.MULTILINE))


def longest_list_run(lines: list[str]) -> int:
    longest = 0
    current = 0
    for line in lines:
        if re.match(r"^\s*(?:[-*+] |\d+[.)] |#\. )", line):
            current += 1
            longest = max(longest, current)
        elif line.strip() == "":
            continue
        else:
            current = 0
    return longest


def collect_structural_signals(text: str, body: str, headings: list[str], rst: bool) -> dict[str, object]:
    lines = text.splitlines()
    ordered_steps = sum(1 for line in lines if re.match(r"^\s*(?:\d+[.)]|#\.)\s+", line))
    bullet_items = sum(1 for line in lines if re.match(r"^\s*[-*+]\s+", line))
    table_rows = sum(1 for line in lines if line.strip().startswith("|") and line.strip().endswith("|"))
    fenced = len(re.findall(r"^```", text, flags=re.MULTILINE)) // 2
    fenced += len(re.findall(r"^~~~", text, flags=re.MULTILINE)) // 2
    indented = 1 if re.search(r"^(?: {4}|\t)\S", text, flags=re.MULTILINE) else 0
    directives = len(re.findall(r"^\.\.\s+(?:code-block|code|literalinclude)::", text, flags=re.MULTILINE)) if rst else 0
    conceptual = [h for h in headings if re.match(CONCEPTUAL_HEADING_PATTERN, h)]
    paragraphs = [p.strip() for p in re.split(r"\n\s*\n", body) if p.strip()]
    placeholders = sum(count_pattern(p, body) for p in PLACEHOLDER_PATTERNS)
    risky = sum(count_pattern(p, text) for p in RISKY_COMMAND_PATTERNS)
    return {
        "ordered_steps": ordered_steps,
        "bullet_items": bullet_items,
        "code_blocks": fenced + directives + indented,
        "fenced_code_blocks": fenced,
        "table_rows": table_rows,
        "option_tables": max(0, table_rows // 3),
        "headings": len(headings),
        "conceptual_headings": conceptual,
        "expected_output_checks": count_pattern(EXPECTED_OUTPUT_PATTERN, body),
        "conditional_branches": count_pattern(r"^\s*(?:if|when|unless)\b|\bif\b.{0,60}\bthen\b", body),
        "verification_markers": count_pattern(r"\b(verify|confirm|check that|you should see)\b", body),
        "rollback_markers": count_pattern(r"\b(roll ?back|restore|undo|revert|backup)\b", body),
        "unresolved_placeholders": placeholders,
        "risky_commands": risky,
        "long_paragraphs": sum(1 for p in paragraphs if len(p.split()) >= 80),
        "longest_list_run": longest_list_run(lines),
        "word_count": len(body.split()),
    }


