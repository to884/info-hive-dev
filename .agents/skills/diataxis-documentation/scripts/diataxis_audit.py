#!/usr/bin/env python3
"""Collect Diátaxis evidence from Markdown-like documentation.

This script is an evidence collector, not a classifier of record. It reports
deterministic structural signals, named risks with the evidence behind them,
and ranked mode hypotheses. The semantic decision — which user need a page
serves — belongs to the reader of this report, who has context the script
does not.

Nothing here is a verdict, and nothing here should be used as a compliance
gate. It uses only the Python standard library and performs no network access.

File-format support: Markdown and MDX are parsed structurally. reStructuredText
gets basic structural support (over/underline titles and section headings,
directives, literal blocks, enumerated lists); everything else is text-level
heuristics. Plain .txt files are scanned as text only.
"""

