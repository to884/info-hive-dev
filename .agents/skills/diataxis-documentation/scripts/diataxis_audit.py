class PatternSet:
    """Terminology-configurable pattern sets.

    Load a JSON file with any of the keys ``title``, ``body``, ``heading`` to
    replace the built-in English patterns (for a translated docs set, or for a
    project with its own vocabulary).
    """

    def __init__(self, title=None, body=None, heading=None):
        self.title = title or DEFAULT_TITLE_PATTERNS
        self.body = body or DEFAULT_BODY_PATTERNS
        self.heading = heading or DEFAULT_HEADING_PATTERNS

    @classmethod
    def load(cls, path: Path) -> "PatternSet":
        data = json.loads(path.read_text(encoding="utf-8"))
        def weighted(key):
            raw = data.get(key)
            if raw is None:
                return None
            return {mode: [(p, int(w)) for p, w in entries] for mode, entries in raw.items()}
        heading = data.get("heading")
        return cls(title=weighted("title"), body=weighted("body"), heading=heading)


@dataclass
class ParsedDoc:
    """One parsed document: everything the scoring and risk passes need.

    Title, body, headings and signals always travel together, so they travel
    as one value rather than as four parallel parameters.
    """

    path: Path
    title: str
    body: str
    headings: list[str]
    signals: dict[str, object]
    declared: str | None

    def n(self, key: str) -> int:
        """Read one structural signal as an integer count."""
        return int(self.signals[key])


