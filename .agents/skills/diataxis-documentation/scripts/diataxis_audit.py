TITLE_CLAIM_PATTERNS = {
    "tutorial": r"\btutorial\b",
    "how-to": r"^\s*how\s+to\b|\bhow-to\b",
    "reference": r"\breference\b",
    "explanation": r"\b(overview|concept|architecture|background|rationale)\b|^\s*why\b",
}


def collect_risks(doc: ParsedDoc, scores: dict[str, int], status: str,
                  candidates: list[str]) -> list[dict[str, str]]:
    risks: list[dict[str, str]] = []

    def add(rule: str, category: str, evidence: str) -> None:
        risks.append({"rule": rule, "category": category, "evidence": evidence})

    top = candidates[0] if candidates else None

    if status == "ambiguous":
        add("strong-competing-user-needs", PURITY,
            f"{candidates[0]} and {candidates[1]} signals are within {AMBIGUITY_GAP_PERCENT}% of each other "
            f"({scores[candidates[0]]} vs {scores[candidates[1]]})")
    if status == "insufficient-context":
        add("insufficient-structural-signal", PURITY,
            f"{doc.n('word_count')} words and no dominant mode signal")

    for rule, test in MODE_INDEPENDENT_RULES:
        evidence = test(doc)
        if evidence:
            add(rule, DEFECT, evidence)

    if doc.signals["conceptual_headings"] and top in {"tutorial", "how-to", "reference"}:
        add("conceptual-sections-inside-action-or-fact-page", PURITY,
            "conceptual headings: " + ", ".join(sorted(set(doc.signals["conceptual_headings"]))[:4]))

    for rule, category, test in MODE_RULES.get(top, {}).get("rules", []):
        evidence = test(doc)
        if evidence:
            add(rule, category, evidence)

    lower_title = doc.title.lower()
    for mode, pattern in TITLE_CLAIM_PATTERNS.items():
        if re.search(pattern, lower_title, flags=re.IGNORECASE) and top and top != mode and status == "clear":
            add("title-conflicts-with-signals", PURITY,
                f"title reads as {mode}; structural signals read as {top}")

    if doc.declared and top and status == "clear" and doc.declared.lower() not in {top, "landing-page", "composite"}:
        add("declared-type-conflicts-with-signals", PURITY,
            f"frontmatter declares doc_type: {doc.declared}; structural signals read as {top}")

    return risks


FOLLOW_UP_SUGGESTIONS = [
    ({"unresolved-placeholders"},
     "Resolve or remove placeholder tokens before publishing."),
    ({"procedure-without-observable-checks", "tutorial-without-observable-checks"},
     "Add an observable result after each substantial action."),
    ({"risky-commands-without-rollback"},
     "Add a backup step and a rollback section, with the warning before the action."),
    ({"how-to-without-verification"},
     "Add a verification step that fails when the task was not performed."),
    ({"long-ungrouped-list"},
     "Group the list under named headings or turn it into a mechanical index."),
    ({"declared-type-conflicts-with-signals"},
     "Reconcile the declared doc_type with the content, or correct the frontmatter."),
]


def make_suggestions(status: str, candidates: list[str], risks: list[dict[str, str]]) -> list[str]:
    suggestions: list[str] = []
    rules = {risk["rule"] for risk in risks}
    top = candidates[0] if candidates else None

    if status == "ambiguous":
        suggestions.append("Establish the reader contract, then decide whether this page serves study or work; split the secondary material.")
    elif status == "insufficient-context":
        suggestions.append("Determine the intended reader need from navigation and neighbouring pages; the page itself does not say.")
    elif top in MODE_RULES:
        suggestions.append(str(MODE_RULES[top]["suggestion"]))

    for triggers, suggestion in FOLLOW_UP_SUGGESTIONS:
        if triggers & rules:
            suggestions.append(suggestion)

    deduped: list[str] = []
    for suggestion in suggestions:
        if suggestion not in deduped:
            deduped.append(suggestion)
    return deduped[:5]


